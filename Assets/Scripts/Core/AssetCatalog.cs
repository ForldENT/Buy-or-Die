        public static List<MarketAsset> Create()
        {
            var list = new List<MarketAsset>(200);
            Add(list, Domestic, AssetKind.Domestic);
            Add(list, Overseas, AssetKind.Overseas);
            Add(list, Coins, AssetKind.Coin);
            return list;
        }

        static void Add(List<MarketAsset> list, string[] rows, AssetKind kind)
        {
            var inv = CultureInfo.InvariantCulture;
            foreach (var row in rows)
            {
                var p = row.Split('|');
                list.Add(new MarketAsset(list.Count, p[0], p[1], p[2], kind,
                    double.Parse(p[3], inv), double.Parse(p[4], inv), double.Parse(p[5], inv)));
            }
        }
